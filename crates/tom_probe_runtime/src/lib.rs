/// Decay kernel infrastructure. The kernel WGSL is
/// generated by `dsl_compiler::belief_decay_wgsl::decay_kernel_wgsl()`
/// (NOT by a literal `const &str` in this file — Phase 3.8 retirement
/// of hand-written WGSL in runtime crates). The 4-kernel
/// `BeliefConsumerGpu` struct that previously held observe/scry/reveal/
/// decay pipelines collapsed to this single `DecayGpu` struct: the 3
/// other consumers are .sim-authored and use the compiler-emitted
/// dispatch helpers.
struct DecayGpu {
    cfg_buf: wgpu::Buffer,
    pipeline: wgpu::ComputePipeline,
    bgl: wgpu::BindGroupLayout,
}

/// Uniform for the compiler-generated decay kernel. Same shape as the
/// retired `BeliefConsumerCfg` so the WGSL field offsets stay stable —
/// the kernel reads `cfg.tick`, `cfg.cell_count`. The other fields are
/// inert padding for std140-like alignment.
#[repr(C)]
#[derive(Copy, Clone, bytemuck::Pod, bytemuck::Zeroable)]
struct DecayCfg {
    observer: u32,
    target_or_subject: u32,
    subject: u32,
    agent_count: u32,
    tick: u32,
    cell_count: u32,
    _pad0: u32,
    _pad1: u32,
}

impl DecayGpu {
    fn new(device: &wgpu::Device) -> Self {
        let cfg_buf = device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("tom_probe_runtime::decay::cfg"),
            size: std::mem::size_of::<DecayCfg>() as u64,
            usage: wgpu::BufferUsages::UNIFORM | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });
        let bgl = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("tom_probe_runtime::decay::bgl"),
            entries: &[
                bgl_uniform(0),
                bgl_storage(1, false), // beliefs_confidence
                bgl_storage(2, true),  // beliefs_tick (read-only)
            ],
        });
        let wgsl_src = dsl_compiler::belief_decay_wgsl::decay_kernel_wgsl();
        let module = device.create_shader_module(wgpu::ShaderModuleDescriptor {
            label: Some("tom_probe_runtime::decay::wgsl"),
            source: wgpu::ShaderSource::Wgsl(wgsl_src.into()),
        });
        let pl = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: Some("tom_probe_runtime::decay::pl"),
            bind_group_layouts: &[&bgl],
            push_constant_ranges: &[],
        });
        let pipeline = device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {
            label: Some("tom_probe_runtime::decay::pipeline"),
            layout: Some(&pl),
            module: &module,
            entry_point: Some("cs_decay"),
            compilation_options: Default::default(),
            cache: None,
        });
        Self { cfg_buf, pipeline, bgl }
    }
}

