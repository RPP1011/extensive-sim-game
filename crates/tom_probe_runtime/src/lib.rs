//! Per-fixture runtime for `assets/sim/tom_probe.sim` — Theory-of-Mind
//! end-to-end probe (post-fix shape).
//!
//! ## What lights up
//!
//! - The Knower SoA (`agent_alive`).
//! - The `BeliefAcquired` event ring + per-tick tail clear.
//! - The `physics_WhatIBelieve` kernel (per-Knower; emits one
//!   `BeliefAcquired { observer: self, subject: self, fact_bit: 1 }`
//!   per tick into the ring).
//! - The `fold_beliefs_flags` kernel (per-event; OR's `fact_bit` into
//!   `view_storage_primary[observer * agent_cap + subject]` via
//!   WGSL native `atomicOr` — no CAS retry, P11 trivial).
//! - Per-(observer, subject) belief storage: 6 SoA columns mirroring
//!   the spec's `BeliefState` block.
//!
//! ## Wave 3 ToM Phase 3.8 — hand-written WGSL retirement
//!
//! Phase 3/3.5/3.6 shipped the observe/scry/reveal/decay verbs as
//! hand-written WGSL kernels (`OBSERVE_WGSL`, `SCRY_WGSL`,
//! `REVEAL_WGSL`, `DECAY_WGSL`) embedded as `const &str` literals in
//! this file. Phase 3.8 retires those four constants per the user's
//! "no hand-written WGSL in runtime crates" constraint:
//!
//! - **observe / scry / reveal**: now `physics @phase(post)` consumer
//!   rules in `assets/sim/tom_probe.sim` (`ApplyObserveBeliefUpdate`,
//!   `ApplyScryBeliefUpdate`, `ApplyRevealBeliefUpdate`). The runtime's
//!   `observe()` / `scry()` / `reveal()` methods now write a synthetic
//!   chronicle record (kind=64 / 65 / 66, engine-aliased) into the
//!   unified `event_ring` via
//!   `engine::gpu::EventRing::append_chronicle_record` and dispatch the
//!   compiler-emitted consumer kernel from .sim.
//! - **decay**: stays as a runtime-dispatched compiler-generated kernel
//!   (no DSL surface for "for_each_agent body" today). The WGSL string
//!   moved out of this crate into
//!   `dsl_compiler::belief_decay_wgsl::decay_kernel_wgsl()` so this
//!   file no longer carries any literal `_WGSL: &str` constant.
//!
//! ## BeliefState SoA (Wave 3 ToM Phase 2)
//!
//! Each (observer, target) pair is described by 6 parallel SoA
//! columns mirroring the spec's BeliefState block:
//!
//! | Field            | Type              | Buffer                       |
//! |------------------|-------------------|------------------------------|
//! | flags            | u32               | `beliefs_flags_primary`      |
//! | last_known_pos   | vec4 (vec3 padded)| `beliefs_pos_primary`        |
//! | last_known_creature_type | u8 (q8)   | `beliefs_type_primary`       |
//! | last_seen_tick   | u32               | `beliefs_tick_primary`       |
//! | confidence       | u8 (q8)           | `beliefs_confidence_primary` |
//! | suspicion        | u8 (q8)           | `beliefs_suspicion_primary`  |
//!
//! Cell indexing across all 6 columns is `observer * agent_count +
//! target` — identical row-major flat layout.
//!
//! ## Expected outcome (FULL FIRE)
//!
//! After N ticks at agent_count = N: `beliefs_flags(i, i) = 1u` for
//! every alive Knower; every off-diagonal `beliefs_flags(i, j != i)
//! = 0u`.

