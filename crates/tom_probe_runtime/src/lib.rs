    /// Wave 3 ToM Phase 4 — erase_belief verb. Queues a synthetic
    /// `EffectEraseBeliefApplied` chronicle record (kind=69) and
    /// dispatches the .sim-authored `physics_ApplyEraseBeliefUpdate`
    /// consumer. The consumer reads the `fields` u8 bitset and clears
    /// the matching cells of `[target * N + subject_idx]` (bit 0 = pos,
    /// 1 = type, 2 = tick, 3 = confidence, 4 = suspicion, 5 = flags).
    ///
    /// Wave 3 ToM Phase 5 — the compiler now fuses
    /// `physics_ApplyEraseBeliefUpdate` and `physics_ApplyDisguise` into
    /// a single kernel `physics_ApplyEraseBeliefUpdate_and_ApplyDisguise`
    /// (both `@phase(post)` PerEvent on the same ring). Each rule-arm is
    /// gated on its own event kind tag (67 vs 69), so dispatching with
    /// a single chronicle record fires only the matching arm.
    pub fn erase_belief(&mut self, caster: u32, target: u32, subject_idx: u32, fields: u8) {
        assert!(caster < self.agent_count);
        assert!(target < self.agent_count);
        assert!(subject_idx < self.agent_count);

        self.queue_clear_tail();

        let mut record = [0u32; CHRONICLE_STRIDE_U32];
        record[0] = KIND_ERASE_BELIEF;
        record[1] = self.tick as u32;
        record[2] = caster;
        record[3] = target;
        record[4] = subject_idx;
        record[5] = fields as u32;
        self.event_ring
            .append_chronicle_record(&self.gpu.queue, &record);

        let cfg = physics_ApplyEraseBeliefUpdate_and_ApplyDisguise::PhysicsApplyEraseBeliefUpdateAndApplyDisguiseCfg {
            event_count: 1,
            tick: self.tick as u32,
            seed: self.seed as u32,
            agent_cap: self.agent_count,
        };
        self.gpu.queue.write_buffer(
            &self.apply_erase_belief_cfg_buf,
            0,
            bytemuck::bytes_of(&cfg),
        );

        let mut encoder =
            self.gpu
                .device
                .create_command_encoder(&wgpu::CommandEncoderDescriptor {
                    label: Some("tom_probe_runtime::erase_belief::encoder"),
                });
        let agent_buffers = AgentBuffers {
            alive_buf: Some(&self.agent_alive_buf),
            ..Default::default()
        };
        let ctx = KernelBindingsContext {
            state: &agent_buffers,
            event_ring: &self.event_ring,
            registry: &self.registry_gpu,
            voxel_grid: None,
            navgrid: None,
            navgrid_cfg: None,
        };
        let extras = physics_ApplyEraseBeliefUpdate_and_ApplyDisguise::PhysicsApplyEraseBeliefUpdateAndApplyDisguiseExtras {
            agent_disguise_expires_at_tick: &self.agent_disguise_expires_at_tick_buf,
            agent_disguise_fake_type: &self.agent_disguise_fake_type_buf,
            beliefs_pos: &self.beliefs_pos_primary,
            beliefs_type: &self.beliefs_type_primary,
            beliefs_tick: &self.beliefs_tick_primary,
            beliefs_confidence: &self.beliefs_confidence_primary,
            beliefs_suspicion: &self.beliefs_suspicion_primary,
            beliefs_flags: &self.beliefs_flags_primary,
            cfg: &self.apply_erase_belief_cfg_buf,
        };
        let bindings = physics_ApplyEraseBeliefUpdate_and_ApplyDisguise::PhysicsApplyEraseBeliefUpdateAndApplyDisguiseBindings::from_context_with_extras(
            &ctx, &extras,
        );
        dispatch::dispatch_physics_applyerasebeliefupdate_and_applydisguise(
            &mut self.cache,
            &bindings,
            &self.gpu.device,
            &mut encoder,
            1,
        );
        self.gpu.queue.submit(Some(encoder.finish()));

        self.beliefs_pos_dirty = true;
        self.beliefs_type_dirty = true;
        self.beliefs_tick_dirty = true;
        self.beliefs_confidence_dirty = true;
        self.beliefs_suspicion_dirty = true;
        self.beliefs_flags_dirty = true;
    }

    /// Wave 3 ToM Phase 5 — disguise verb. Queues a synthetic
    /// `EffectDisguiseApplied` chronicle record (kind=67) and dispatches
    /// the .sim-authored `physics_ApplyDisguise` consumer. The consumer
    /// decodes payload_a (= `(duration_ticks << 8) | fake_type`), then
    /// writes the per-agent `disguise_expires_at_tick` (=
    /// `world.tick + duration`) and `disguise_fake_type` (= low byte)
    /// SoA columns at slot `caster`.
    ///
    /// Subsequent observe calls consult these columns at consume-time
    /// and substitute `disguise_fake_type` for the true `creature_type`
    /// when the disguise window is still active.
    pub fn disguise(&mut self, caster: u32, fake_type: u8, duration_ticks: u32) {
        assert!(caster < self.agent_count);
        // Pack the payload exactly as the GPU dispatcher does for kind 36
        // (see `cg::emit::wgsl_body` Disguise arm).
        let payload_a = (duration_ticks << 8) | (fake_type as u32);

        self.queue_clear_tail();

        let mut record = [0u32; CHRONICLE_STRIDE_U32];
        record[0] = KIND_DISGUISE;
        record[1] = self.tick as u32;
        record[2] = caster;
        record[3] = caster; // implicit-target rule: target = caster for self-cast
        record[4] = payload_a;
        self.event_ring
            .append_chronicle_record(&self.gpu.queue, &record);

        let cfg = physics_ApplyEraseBeliefUpdate_and_ApplyDisguise::PhysicsApplyEraseBeliefUpdateAndApplyDisguiseCfg {
            event_count: 1,
            tick: self.tick as u32,
            seed: self.seed as u32,
            agent_cap: self.agent_count,
        };
        self.gpu.queue.write_buffer(
            &self.apply_disguise_cfg_buf,
            0,
            bytemuck::bytes_of(&cfg),
        );

        let mut encoder =
            self.gpu
                .device
                .create_command_encoder(&wgpu::CommandEncoderDescriptor {
                    label: Some("tom_probe_runtime::disguise::encoder"),
                });
        let agent_buffers = AgentBuffers {
            alive_buf: Some(&self.agent_alive_buf),
            ..Default::default()
        };
        let ctx = KernelBindingsContext {
            state: &agent_buffers,
            event_ring: &self.event_ring,
            registry: &self.registry_gpu,
            voxel_grid: None,
            navgrid: None,
            navgrid_cfg: None,
        };
        let extras = physics_ApplyEraseBeliefUpdate_and_ApplyDisguise::PhysicsApplyEraseBeliefUpdateAndApplyDisguiseExtras {
            agent_disguise_expires_at_tick: &self.agent_disguise_expires_at_tick_buf,
            agent_disguise_fake_type: &self.agent_disguise_fake_type_buf,
            beliefs_pos: &self.beliefs_pos_primary,
            beliefs_type: &self.beliefs_type_primary,
            beliefs_tick: &self.beliefs_tick_primary,
            beliefs_confidence: &self.beliefs_confidence_primary,
            beliefs_suspicion: &self.beliefs_suspicion_primary,
            beliefs_flags: &self.beliefs_flags_primary,
            cfg: &self.apply_disguise_cfg_buf,
        };
        let bindings = physics_ApplyEraseBeliefUpdate_and_ApplyDisguise::PhysicsApplyEraseBeliefUpdateAndApplyDisguiseBindings::from_context_with_extras(
            &ctx, &extras,
        );
        dispatch::dispatch_physics_applyerasebeliefupdate_and_applydisguise(
            &mut self.cache,
            &bindings,
            &self.gpu.device,
            &mut encoder,
            1,
        );
        self.gpu.queue.submit(Some(encoder.finish()));

        self.agent_disguise_expires_at_tick_dirty = true;
        self.agent_disguise_fake_type_dirty = true;
    }

    /// Read the agent SoA `disguise_expires_at_tick` column.
    pub fn agent_disguise_expires_at_tick(&mut self) -> &[u32] {
        if self.agent_disguise_expires_at_tick_dirty {
            let bytes = (self.agent_disguise_expires_at_tick_cache.len() as u64) * 4;
            let mut encoder = self.gpu.device.create_command_encoder(
                &wgpu::CommandEncoderDescriptor {
                    label: Some("tom_probe_runtime::agent_disguise_expires::readback"),
                },
            );
            encoder.copy_buffer_to_buffer(
                &self.agent_disguise_expires_at_tick_buf,
                0,
                &self.agent_disguise_expires_at_tick_staging,
                0,
                bytes,
            );
            self.gpu.queue.submit(Some(encoder.finish()));
            let slice = self.agent_disguise_expires_at_tick_staging.slice(..bytes);
            slice.map_async(wgpu::MapMode::Read, |_| {});
            self.gpu.device.poll(wgpu::PollType::Wait).expect("poll");
            let mapped = slice.get_mapped_range();
            let raw: &[u32] = bytemuck::cast_slice(&mapped);
            self.agent_disguise_expires_at_tick_cache.copy_from_slice(raw);
            drop(mapped);
            self.agent_disguise_expires_at_tick_staging.unmap();
            self.agent_disguise_expires_at_tick_dirty = false;
        }
        &self.agent_disguise_expires_at_tick_cache
    }

