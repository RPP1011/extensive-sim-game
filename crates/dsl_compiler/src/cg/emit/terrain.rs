//! Emit `terrain_gen.rs` source from a lowered `TerrainIr`. The output
//! is written by per-runtime `build.rs` into `OUT_DIR/terrain_gen.rs`
//! and `include!`-d by the runtime. The compiler itself never writes
//! to OUT_DIR — that is the build.rs caller's job.

use crate::cg::lower::{TerrainIr, TerrainLayerIr};
use std::fmt::Write;

/// Emit a `terrain_gen.rs` source string from a lowered [`TerrainIr`].
///
/// The returned string is deterministic: the same `ir` always produces
/// byte-identical output (no hash-map iteration, no toolchain-sensitive
/// formatting). This is required by T9, which hash-roundtrip-compiles
/// the emitted output.
pub fn emit_terrain(ir: &TerrainIr) -> String {
    let mut out = String::new();
    writeln!(out, "// @generated by dsl_compiler::emit::terrain — DO NOT EDIT").unwrap();
    writeln!(out, "// Generated terrain initialiser. Source: a `.sim` `terrain {{ }}` block.").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub const EXTENT: u32 = {};", ir.extent).unwrap();
    writeln!(out, "pub const CELL_SIZE: f32 = {:?};", ir.cell_size).unwrap();
    // Emit seed_purpose as hex with underscore separator matching the DSL
    // literal style: 0xHHHH_LLLL (high 16 bits _ low 16 bits).
    writeln!(
        out,
        "pub const SEED_PURPOSE: u32 = 0x{:04X}_{:04X};",
        ir.seed_purpose >> 16,
        ir.seed_purpose & 0xFFFF
    )
    .unwrap();
    writeln!(out).unwrap();

    // Material rows.
    writeln!(out, "static MATERIAL_ROWS: &[::engine_voxel::MaterialRow] = &[").unwrap();
    for m in &ir.materials {
        writeln!(
            out,
            "    ::engine_voxel::MaterialRow {{ id: {}u8, walkable: {}, hardness: {}u8, biome_tag_hash: 0x{:08X}u32, color: 0x{:06X}u32, movement_cost: {:?} }},",
            m.id, m.walkable, m.hardness, m.biome_tag_hash, m.color, m.movement_cost
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(
        out,
        "pub static MATERIALS: ::engine_voxel::MaterialTable ="
    )
    .unwrap();
    writeln!(out, "    ::engine_voxel::MaterialTable::new(MATERIAL_ROWS);").unwrap();
    writeln!(out).unwrap();

    // generate_terrain function.
    writeln!(
        out,
        "pub fn generate_terrain(world_seed: u64) -> ::engine_voxel::VoxelTerrain {{"
    )
    .unwrap();
    writeln!(out, "    let _ = world_seed; // unused until noise layers land").unwrap();
    writeln!(
        out,
        "    let mut t = ::engine_voxel::VoxelTerrain::with_extent_and_materials(EXTENT, MATERIALS);"
    )
    .unwrap();
    for (i, layer) in ir.layers.iter().enumerate() {
        let idx = (i + 1) as u32;
        match layer {
            TerrainLayerIr::Fill { material_id } => {
                writeln!(out, "    // layer {}: fill", idx).unwrap();
                writeln!(
                    out,
                    "    ::engine_voxel::terrain_layers::layer_fill(&mut t, {}u8);",
                    material_id
                )
                .unwrap();
            }
        }
    }
    writeln!(out, "    t").unwrap();
    writeln!(out, "}}").unwrap();

    out
}
